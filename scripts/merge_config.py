#!/usr/bin/env python3
import os
import sys
from pathlib import Path

if len(sys.argv) != 4:
    print("usage: merge_config.py <raw_sub_yaml> <out_config_yaml> <ui_dir>", file=sys.stderr)
    sys.exit(2)

raw_path = Path(sys.argv[1])
out_path = Path(sys.argv[2])
ui_dir = Path(sys.argv[3]).resolve()

raw = raw_path.read_text(encoding="utf-8", errors="ignore") if raw_path.exists() else ""
# 这些顶层字段由本包固定控制，避免订阅覆盖端口、面板和启动行为。
override_keys = {
    "port", "socks-port", "mixed-port", "redir-port", "tproxy-port",
    "allow-lan", "bind-address", "mode", "log-level", "ipv6",
    "external-controller", "external-ui", "external-ui-name", "external-ui-url",
    "secret", "profile", "geodata-mode", "geodata-loader"
}

lines = raw.splitlines()
kept = []
skip = False
for line in lines:
    stripped = line.strip()
    if not stripped or stripped.startswith("#"):
        if not skip:
            kept.append(line)
        continue
    is_top = (line[:1] not in (" ", "\t", "-")) and (":" in line)
    if is_top:
        key = line.split(":", 1)[0].strip().strip('"\'')
        skip = key in override_keys
    if not skip:
        kept.append(line)

header = f"""# Generated by clash-meta-mihomo-linux-amd64/update-config.sh
# 本文件会在更新订阅时重写；自定义项建议改 update-config.sh 或单独备份。
port: 7892
socks-port: 7891
mixed-port: 17890
allow-lan: false
bind-address: 127.0.0.1
mode: rule
log-level: info
external-controller: 127.0.0.1:19090
external-ui: {ui_dir.as_posix()}
secret: ""
profile:
  store-selected: true
  store-fake-ip: true
"""
body = "\n".join(kept).strip()
out_path.write_text(header + ("\n" + body + "\n" if body else "\n"), encoding="utf-8")
